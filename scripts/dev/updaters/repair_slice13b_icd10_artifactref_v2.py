from __future__ import annotations

from pathlib import Path
from typing import Any
import re

import yaml


ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "src" / "pegasus"
CONFIG = ROOT / "config" / "registries"

SUBSTRATE_PATH = SRC / "she" / "substrate.py"
SOURCE_FIELDS_YAML = CONFIG / "source_fields.yaml"
UNIT_YAML = CONFIG / "unit.yaml"
CARRIER_YAML = CONFIG / "carrier.yaml"
APPLY_UPDATER = ROOT / "scripts" / "dev" / "updaters" / "apply_slice13b_registry_backed_source_semantics.py"
AUDIT_PATH = ROOT / "scripts" / "dev" / "audits" / "audit_slice13b_registry_backed_source_fields.py"
TEST_REGISTRY_PATH = ROOT / "tests" / "unit" / "test_registry_source_fields_yaml.py"
TEST_SHE_PATH = ROOT / "tests" / "unit" / "test_she_source_registry_yaml_backed.py"

ICD_COLUMNS = {
    "SIM-DO": {"underlying_icd_norm", "associated_conditions_norm"},
    "SIH-RD": {"principal_icd_norm"},
    "SINASC": {"anomaly_icd_code"},
}


def _read(path: Path) -> str:
    if not path.exists():
        raise FileNotFoundError(path)
    return path.read_text(encoding="utf-8")


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8")


def _load_yaml(path: Path) -> dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(path)
    payload = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(payload, dict):
        raise RuntimeError(f"expected mapping YAML at {path}")
    return payload


def _dump_yaml(path: Path, payload: dict[str, Any]) -> None:
    path.write_text(
        yaml.safe_dump(payload, sort_keys=False, allow_unicode=True, width=120),
        encoding="utf-8",
    )


def _entries_as_dict(payload: dict[str, Any]) -> tuple[dict[str, Any], str]:
    entries = payload.setdefault("entries", {})
    if isinstance(entries, dict):
        return entries, "dict"
    if isinstance(entries, list):
        mapped: dict[str, Any] = {}
        for item in entries:
            if isinstance(item, dict):
                key = item.get("id") or item.get("unit_id") or item.get("carrier_id") or item.get("tag") or item.get("role_id")
                if key is not None:
                    mapped[str(key)] = item
        return mapped, "list"
    raise RuntimeError("registry entries must be a mapping or list")


def _replace_entries(payload: dict[str, Any], entries: dict[str, Any], kind: str) -> None:
    if kind == "dict":
        payload["entries"] = entries
    else:
        payload["entries"] = list(entries.values())


def patch_unit_registry() -> None:
    payload = _load_yaml(UNIT_YAML)
    entries, kind = _entries_as_dict(payload)
    if "ICD10" not in entries:
        if kind == "dict":
            entries["ICD10"] = {
                "dimension": "diagnostic_code",
                "additive": False,
                "description": "ICD-10 diagnostic code mark. Not a count measure; code-specific counts are generated by EFG operators.",
            }
        else:
            entries["ICD10"] = {
                "id": "ICD10",
                "status": "active",
                "description": "ICD-10 diagnostic code mark. Not a count measure; code-specific counts are generated by EFG operators.",
                "warnings": [],
                "dimension": "diagnostic_code",
                "additive": False,
            }
    _replace_entries(payload, entries, kind)
    _dump_yaml(UNIT_YAML, payload)


def _append_allowed_unit(spec: dict[str, Any], unit: str) -> None:
    allowed = spec.get("allowed_units")
    if allowed is None:
        spec["allowed_units"] = [unit]
        return
    if isinstance(allowed, str):
        values = [allowed]
    else:
        values = list(allowed)
    if unit not in values:
        values.append(unit)
    spec["allowed_units"] = values


def patch_carrier_registry() -> None:
    payload = _load_yaml(CARRIER_YAML)
    entries, kind = _entries_as_dict(payload)
    for carrier_id in ["Deaths", "HospitalAdmissions", "LiveBirths"]:
        spec = entries.get(carrier_id)
        if isinstance(spec, dict):
            _append_allowed_unit(spec, "ICD10")
    _replace_entries(payload, entries, kind)
    _dump_yaml(CARRIER_YAML, payload)


def _looks_like_source_field_entry(node: dict[str, Any]) -> bool:
    return any(k in node for k in ("source_system", "column_name", "column", "raw_field", "canonical_field")) and "unit" in node


def _source_system(node: dict[str, Any]) -> str | None:
    value = node.get("source_system")
    return str(value) if value is not None else None


def _column_name(node: dict[str, Any]) -> str | None:
    for key in ("column_name", "column", "raw_field", "canonical_field"):
        value = node.get(key)
        if value is not None:
            return str(value)
    entry_id = node.get("id")
    if isinstance(entry_id, str) and "." in entry_id:
        return entry_id.rsplit(".", 1)[-1]
    return None


def _patch_source_field_node(node: dict[str, Any]) -> bool:
    source = _source_system(node)
    col = _column_name(node)
    if source in ICD_COLUMNS and col in ICD_COLUMNS[source]:
        node["unit"] = "ICD10"
        node.setdefault("field_kind", "marked_functional")
        node.setdefault("quality_role", "diagnostic_code")
        # A source ICD code column is a diagnostic mark, not an already-counted event measure.
        if node.get("aggregation") == "additive":
            node["aggregation"] = "non_aggregable"
        return True
    return False


def _walk_and_patch_source_fields(value: Any) -> int:
    changed = 0
    if isinstance(value, dict):
        if _looks_like_source_field_entry(value) and _patch_source_field_node(value):
            changed += 1
        for child in value.values():
            changed += _walk_and_patch_source_fields(child)
    elif isinstance(value, list):
        for child in value:
            changed += _walk_and_patch_source_fields(child)
    return changed


def patch_source_fields_registry() -> None:
    payload = _load_yaml(SOURCE_FIELDS_YAML)
    changed = _walk_and_patch_source_fields(payload)
    if changed == 0:
        text = SOURCE_FIELDS_YAML.read_text(encoding="utf-8")
        # Conservative textual fallback for common generated YAML shapes.
        text = re.sub(
            r"(source_system:\s*SIM-DO[\s\S]{0,500}?column_name:\s*underlying_icd_norm[\s\S]{0,500}?unit:\s*)counts",
            r"\1ICD10",
            text,
            count=1,
        )
        text = re.sub(
            r"(source_system:\s*SIH-RD[\s\S]{0,500}?column_name:\s*principal_icd_norm[\s\S]{0,500}?unit:\s*)counts",
            r"\1ICD10",
            text,
            count=1,
        )
        text = re.sub(
            r"(source_system:\s*SINASC[\s\S]{0,500}?column_name:\s*anomaly_icd_code[\s\S]{0,500}?unit:\s*)counts",
            r"\1ICD10",
            text,
            count=1,
        )
        SOURCE_FIELDS_YAML.write_text(text.rstrip() + "\n", encoding="utf-8")
    else:
        _dump_yaml(SOURCE_FIELDS_YAML, payload)


def patch_substrate_artifact_ref_default() -> None:
    text = _read(SUBSTRATE_PATH)
    old = '''@dataclass(frozen=True)\nclass SourceArtifactRef:\n    path: str\n    source_system: str\n    artifact_role: str\n    provenance_mode: str\n    source_manifest_hash: str | None = None\n    artifact_hash: str | None = None\n'''
    new = '''@dataclass(frozen=True)\nclass SourceArtifactRef:\n    path: str\n    source_system: str\n    artifact_role: str = "processed_events"\n    provenance_mode: str = "fixture"\n    source_manifest_hash: str | None = None\n    artifact_hash: str | None = None\n'''
    if old in text:
        text = text.replace(old, new, 1)
    elif 'artifact_role: str = "processed_events"' in text and 'provenance_mode: str = "fixture"' in text:
        pass
    else:
        text = re.sub(
            r"class SourceArtifactRef:\n(\s+path: str\n\s+source_system: str\n)\s+artifact_role: str\n\s+provenance_mode: str",
            "class SourceArtifactRef:\n\\1    artifact_role: str = \"processed_events\"\n    provenance_mode: str = \"fixture\"",
            text,
            count=1,
        )
    _write(SUBSTRATE_PATH, text)


def patch_generated_tests_and_audit_expectations() -> None:
    # Slice 13B generated a few checks/audits that treated diagnostic-code marks as counts.
    # Preserve older Slice 13A expectation and TDD source-field typing: ICD fields are ICD10 marks.
    replacements = {
        '"counts"': '"ICD10"',
        "'counts'": "'ICD10'",
    }
    for path in [TEST_REGISTRY_PATH, TEST_SHE_PATH, AUDIT_PATH]:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        original = text
        if "underlying_icd_norm" in text:
            # Target only local lines mentioning underlying_icd_norm when possible.
            lines = []
            for line in text.splitlines():
                if "underlying_icd_norm" in line or "SIM-DO.underlying_icd_norm" in line:
                    for old, new in replacements.items():
                        line = line.replace(old, new)
                    line = line.replace("Deaths/counts", "Deaths/ICD10")
                lines.append(line)
            text = "\n".join(lines) + "\n"
        if text != original:
            path.write_text(text, encoding="utf-8")


def patch_apply_updater_text() -> None:
    if not APPLY_UPDATER.exists():
        return
    text = APPLY_UPDATER.read_text(encoding="utf-8")
    original = text
    # Future replay should keep SourceArtifactRef backward compatible.
    text = text.replace(
        'artifact_role: str\\n    provenance_mode: str',
        'artifact_role: str = "processed_events"\\n    provenance_mode: str = "fixture"',
    )
    text = text.replace(
        'artifact_role: str\n    provenance_mode: str',
        'artifact_role: str = "processed_events"\n    provenance_mode: str = "fixture"',
    )
    # Future replay should not encode underlying ICD marks as generic counts.
    text = text.replace('column_name: underlying_icd_norm\n        unit: counts', 'column_name: underlying_icd_norm\n        unit: ICD10')
    text = text.replace('column_name: principal_icd_norm\n        unit: counts', 'column_name: principal_icd_norm\n        unit: ICD10')
    text = text.replace('column_name: anomaly_icd_code\n        unit: counts', 'column_name: anomaly_icd_code\n        unit: ICD10')
    if text != original:
        APPLY_UPDATER.write_text(text.rstrip() + "\n", encoding="utf-8")


def main() -> None:
    patch_unit_registry()
    patch_carrier_registry()
    patch_source_fields_registry()
    patch_substrate_artifact_ref_default()
    patch_generated_tests_and_audit_expectations()
    patch_apply_updater_text()
    print("Slice 13B repair v2 applied: ICD source fields retain ICD10 unit and SourceArtifactRef has default artifact_role/provenance_mode.")


if __name__ == "__main__":
    main()
